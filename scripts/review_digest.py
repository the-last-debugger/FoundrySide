"""Generate a compact, grouped digest of the review queue.

The queue is an append-only ledger and has grown long enough that reviewing it means reading forty
rows in ID order. This produces the view a reviewer actually needs: open items grouped by theme,
most consequential first, with the exact revision each verdict should attach to, and superseded
rows called out rather than silently dropped.

    python scripts/review_digest.py

Writes docs/REVIEW_DIGEST.md. Regenerating is idempotent.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
QUEUE = ROOT / "docs" / "COLLAB" / "REVIEW_QUEUE.md"
OUT = ROOT / "docs" / "REVIEW_DIGEST.md"

ROW_RE = re.compile(r"^\|\s*(?P<id>RQ-\d+)\s*\|(?P<rest>.*)$")

# Themes, in the order a reviewer should encounter them: what could change a conclusion first.
THEMES = [
    ("Correctness of a result", ("RQ-027", "RQ-037", "RQ-026", "RQ-038", "RQ-039", "RQ-029",
                                 "RQ-033", "RQ-034", "RQ-024", "RQ-025")),
    ("Evidence and reproducibility", ("RQ-031", "RQ-040", "RQ-047", "RQ-048", "RQ-036", "RQ-032")),
    ("Scope and claims", ("RQ-028", "RQ-035", "RQ-041", "RQ-030", "RQ-043", "RQ-044", "RQ-045")),
    ("Contingency and product", ("RQ-042", "RQ-049", "RQ-046")),
]


def rows() -> list[dict]:
    out = []
    for line in QUEUE.read_text(encoding="utf-8").splitlines():
        m = ROW_RE.match(line)
        if not m:
            continue
        cells = [c.strip() for c in m.group("rest").split("|")]
        # rest = description, artefacts, revision, state, note, author
        out.append({"id": m.group("id"),
                    "desc": cells[0] if len(cells) > 0 else "",
                    "files": cells[1] if len(cells) > 1 else "",
                    "rev": cells[2] if len(cells) > 2 else "",
                    "state": cells[3] if len(cells) > 3 else "",
                    "note": cells[4] if len(cells) > 4 else ""})
    return out


def write() -> int:
    """Regenerate the digest. Callable from other scripts; main() wraps it for the CLI."""
    all_rows = rows()
    by_id = {r["id"]: r for r in all_rows}
    accepted = [r for r in all_rows if r["state"] == "accepted"]
    changes = [r for r in all_rows if r["state"] == "changes_requested"]
    pending = [r for r in all_rows if r["state"] == "ready_for_review"]

    used: set[str] = set()
    lines = [
        "<!-- generated-by: review_digest.py -->",
        "",
        "# Review digest",
        "",
        "Generated by `python scripts/review_digest.py` from `docs/COLLAB/REVIEW_QUEUE.md`.",
        "Regenerate rather than edit; the queue is the source of truth.",
        "",
        f"- **{len(all_rows)}** rows: **{len(accepted)}** accepted, **{len(changes)}** changes "
        f"requested, **{len(pending)}** awaiting review.",
        "",
        "Each verdict should attach to the exact revision in its row. Rows are grouped by what a",
        "reviewer would change by accepting them, not by ID.",
        "",
    ]

    for title, ids in THEMES:
        group = [by_id[i] for i in ids if i in by_id and by_id[i]["state"] != "accepted"]
        if not group:
            continue
        lines += [f"## {title}", "",
                  "| Row | Revision | State | What it is |",
                  "| --- | --- | --- | --- |"]
        for r in group:
            used.add(r["id"])
            lines.append(f"| {r['id']} | `{r['rev']}` | {r['state']} | {r['desc']} |")
        lines.append("")

    leftovers = [r for r in all_rows if r["id"] not in used and r["state"] != "accepted"]
    if leftovers:
        lines += ["## Other open items", "",
                  "| Row | Revision | State | What it is |",
                  "| --- | --- | --- | --- |"]
        for r in leftovers:
            lines.append(f"| {r['id']} | `{r['rev']}` | {r['state']} | {r['desc']} |")
        lines.append("")

    if accepted:
        lines += ["## Accepted", "",
                  "| Row | Revision | |", "| --- | --- | --- |"]
        for r in accepted:
            lines.append(f"| {r['id']} | `{r['rev']}` | {r['desc']} |")
        lines.append("")

    # Movement since the cited revision, computed rather than asserted. A row whose files have
    # changed since its revision should be reviewed against the latest state, and that is a fact
    # about the repository, not an editorial judgement about which rows matter.
    moved = []
    for r in [x for x in all_rows if x["state"] != "accepted"]:
        files = [f.strip() for f in r["files"].split(",") if f.strip()]
        if not files or not r["rev"]:
            continue
        proc = subprocess.run(["git", "diff", "--name-only", f"{r['rev']}..HEAD", "--", *files],
                              cwd=ROOT, capture_output=True, text=True)
        changed = [f for f in proc.stdout.splitlines() if f.strip()]
        if changed:
            moved.append((r["id"], r["rev"], len(changed)))

    lines += [
        "## Moved since the cited revision",
        "",
        "Rows whose files have changed after the revision they cite. Reviewing these against the",
        "cited revision would judge a state that no longer exists; the verdict should attach to a",
        "current revision, or the row should be updated first.",
        "",
    ]
    if moved:
        lines += ["| Row | Cited | Files changed since |", "| --- | --- | --- |"]
        for rid, rev, count in moved:
            lines.append(f"| {rid} | {rev} | {count} |")
    else:
        lines.append("None: every open row cites a revision at or after its last change.")
    lines.append("")

    OUT.write_text("\n".join(lines), encoding="utf-8")
    try:
        shown = OUT.relative_to(ROOT)
    except ValueError:
        shown = OUT
    print(f"wrote {shown}: {len(all_rows)} rows "
          f"({len(accepted)} accepted, {len(changes)} changes, {len(pending)} pending)")
    return 0



def main() -> int:
    return write()


if __name__ == "__main__":
    raise SystemExit(main())
