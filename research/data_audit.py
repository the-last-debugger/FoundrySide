"""Workstream 6: data and timing audit.

Before attributing a failure to the absence of signal, check that the data are what they are
supposed to be. Cheap checks, each of which would invalidate results if it failed:

1. duplicate fixtures — the same league, date, home and away appearing twice;
2. a team playing twice on the same date in the same league;
3. result and price completeness;
4. season length plausibility — a season with far too many or too few fixtures;
5. kickoff times outside a plausible window.

    python research/data_audit.py

Writes research/DATA_AUDIT.md.
"""

from __future__ import annotations

import math
import statistics
import sys
from collections import Counter, defaultdict
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "research"))

import analyse        # noqa: E402
import report_stamp   # noqa: E402

OUT = ROOT / "research" / "DATA_AUDIT.md"



def classify_price(row: dict) -> str:
    """'ok', 'missing' or 'invalid' for a complete over/under 2.5 closing pair.

    Both sides are checked, and both must be finite and greater than 1.0. An earlier version
    read only the over side, so a row with a usable over price and a broken under price passed
    as complete.
    """
    try:
        over, under = float(row["PC>2.5"]), float(row["PC<2.5"])
    except (KeyError, TypeError, ValueError):
        return "missing"
    if not (math.isfinite(over) and math.isfinite(under)):
        return "invalid"
    if over <= 1.0 or under <= 1.0:
        return "invalid"
    return "ok"


def main() -> int:
    rows = analyse.load()
    total = len(rows)

    keys = Counter()
    team_days: dict[tuple[str, str, str], int] = defaultdict(int)
    missing_result = 0
    missing_price = 0
    invalid_price = 0
    bad_times = 0
    per_season: dict[tuple[str, str], int] = Counter()

    for r in rows:
        league, season = r["_league"], r["_season"]
        per_season[(league, season)] += 1
        keys[(league, r["Date"], r["HomeTeam"], r["AwayTeam"])] += 1
        team_days[(league, r["Date"], r["HomeTeam"])] += 1
        team_days[(league, r["Date"], r["AwayTeam"])] += 1
        try:
            int(r["FTHG"]), int(r["FTAG"])
        except (KeyError, TypeError, ValueError):
            missing_result += 1
        status = classify_price(r)
        if status == "missing":
            missing_price += 1
        elif status == "invalid":
            invalid_price += 1
        try:
            hour = int(r["Time"][:2])
            if hour < 8 or hour > 23:
                bad_times += 1
        except (KeyError, TypeError, ValueError):
            bad_times += 1

    duplicates = [k for k, c in keys.items() if c > 1]
    double_headers = [k for k, c in team_days.items() if c > 1]
    season_sizes = sorted(per_season.values())
    median_size = statistics.median(season_sizes) if season_sizes else 0

    checks = [
        ("duplicate fixtures", len(duplicates), 0),
        ("team playing twice on one date", len(double_headers), 0),
        ("rows without a full-time score", missing_result, 0),
        ("rows with a missing O/U price side", missing_price, "expected small"),
        ("rows with a present but invalid O/U price", invalid_price, 0),
        ("kickoff times outside 08:00–23:59", bad_times, "expected small"),
    ]

    doc = f"""{report_stamp.stamp(Path(__file__))}

# Data and timing audit

Generated by `python research/data_audit.py` over {total:,} source rows. This is the check that
should precede any claim that the data lack signal.

| Check | Count | Expected |
| --- | --- | --- |
""" + "\n".join(f"| {name} | {count:,} | {expected} |" for name, count, expected in checks) + f"""

- League-seasons: **{len(per_season)}**; fixtures per season median **{median_size:.0f}**,
  range {min(season_sizes)}–{max(season_sizes)}.

## Why each check matters

A duplicate fixture would double-count one match in every fit and every score. A team playing
twice on a date would mean the fixture list is inconsistent and the rest calculation is
meaningless. Missing scores would silently drop rows from the outcome side while leaving them in
the price side. Extreme kickoff times would indicate a timezone or DST defect — the exact failure
the cutoff audit was built to catch, one level up.

## What this audit does not check

- Whether the *values* are correct: a mis-typed score is indistinguishable from a real one here.
- Whether the prices are the ones that were actually available at T−90 — there is no quote
  timestamp to compare against, and that limitation remains in every report.
- Result corrections after publication: the corpus records a final state, not the history of it.

## Standing caveat

Passing this audit means the corpus is internally consistent. It does not mean the corpus is
complete, current, or free of selection effects in which fixtures were included.
"""
    OUT.write_text(doc, encoding="utf-8")

    for name, count, expected in checks:
        print(f"{name}: {count} (expected {expected})")
    print(f"seasons={len(per_season)} median_fixtures={median_size:.0f}")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
